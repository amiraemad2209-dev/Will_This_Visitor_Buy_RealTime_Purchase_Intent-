import streamlit as st
import pandas as pd
import numpy as np
import joblib
from pathlib import Path

st.set_page_config(page_title="Purchase Intent Analyzer", page_icon="🛍️", layout="wide")

MODEL_PATH = Path(__file__).parent / "artifacts" / "purchase_intent_pipeline.joblib"

st.title("🛍️ Will This Visitor Buy?")
st.write(
    "Upload a CSV containing browsing-session features. The saved model will estimate "
    "purchase probability for each session. **Uploading a file does not train or retrain the model.**"
)

@st.cache_resource
def load_artifact(path):
    return joblib.load(path)

if not MODEL_PATH.exists():
    st.error(
        "The trained model was not found. Run all cells in purchase_intent_training.ipynb "
        "to create artifacts/purchase_intent_pipeline.joblib, then restart the app."
    )
    st.stop()

artifact = load_artifact(MODEL_PATH)
model = artifact["pipeline"]
feature_columns = artifact["feature_columns"]

st.caption(f"Loaded saved model: {artifact.get('model_name', 'Trained classifier')}")

uploaded_file = st.file_uploader("Upload session data (CSV)", type=["csv"])

if uploaded_file is not None:
    try:
        incoming = pd.read_csv(uploaded_file)
    except Exception as exc:
        st.error(f"Could not read this CSV: {exc}")
        st.stop()

    st.subheader("1. File preview")
    st.write(f"Rows: **{len(incoming):,}** · Columns: **{len(incoming.columns)}**")
    st.dataframe(incoming.head(10), use_container_width=True)

    # Revenue is an optional label for retrospective evaluation only; never passed to model.predict.
    has_actual = "Revenue" in incoming.columns
    X_new = incoming.drop(columns=["Revenue"], errors="ignore").copy()

    missing = [c for c in feature_columns if c not in X_new.columns]
    extra = [c for c in X_new.columns if c not in feature_columns]

    if missing:
        st.error("The uploaded CSV is missing required feature columns: " + ", ".join(missing))
        st.info("Use the sample CSV generated by the training notebook as a template.")
        st.stop()

    if extra:
        st.warning("Extra columns will be ignored: " + ", ".join(extra))

    X_new = X_new[feature_columns]

    if X_new.empty:
        st.warning("The uploaded file contains no session rows.")
        st.stop()

    try:
        probabilities = model.predict_proba(X_new)[:, 1]
    except Exception as exc:
        st.error(
            "Prediction failed. Check that the CSV uses the same feature meanings and data "
            f"types as the training dataset. Details: {exc}"
        )
        st.stop()

    # Illustrative business policy; thresholds are not trained model parameters.
    def suggested_action(p):
        if p >= 0.65:
            return "No action"
        elif p >= 0.30:
            return "Show chat assistant"
        return "Consider coupon"

    results = incoming.copy()
    results["purchase_probability"] = probabilities
    results["prediction"] = np.where(probabilities >= 0.50, "Likely to purchase", "Unlikely to purchase")
    results["suggested_action"] = [suggested_action(p) for p in probabilities]

    st.subheader("2. Prediction summary")
    c1, c2, c3 = st.columns(3)
    c1.metric("Sessions analyzed", f"{len(results):,}")
    c2.metric("Likely to purchase", f"{(probabilities >= 0.50).sum():,}")
    c3.metric("Average purchase probability", f"{probabilities.mean():.1%}")

    st.subheader("3. Suggested actions")
    st.bar_chart(results["suggested_action"].value_counts())
    st.subheader("4. Session-level results")
    st.dataframe(
        results.sort_values("purchase_probability", ascending=False),
        use_container_width=True
    )

    csv_bytes = results.to_csv(index=False).encode("utf-8")
    st.download_button(
        "Download predictions CSV",
        data=csv_bytes,
        file_name="purchase_intent_predictions.csv",
        mime="text/csv"
    )

    if has_actual:
        st.info(
            "The uploaded file contains a Revenue column. It was excluded from prediction inputs. "
            "It can be used only for retrospective comparison because actual outcomes are already known."
        )
        actual = incoming["Revenue"].astype(str).str.strip().str.lower().map(
            {"true": 1, "1": 1, "yes": 1, "false": 0, "0": 0, "no": 0}
        )
        valid = actual.notna()
        if valid.any():
            from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score
            y_true = actual[valid].astype(int)
            y_prob = probabilities[valid.to_numpy()]
            y_pred = (y_prob >= 0.50).astype(int)
            st.subheader("5. Retrospective comparison (only when Revenue labels are present)")
            m1, m2, m3, m4 = st.columns(4)
            m1.metric("Accuracy", f"{accuracy_score(y_true, y_pred):.3f}")
            m2.metric("Precision", f"{precision_score(y_true, y_pred, zero_division=0):.3f}")
            m3.metric("Recall", f"{recall_score(y_true, y_pred, zero_division=0):.3f}")
            m4.metric("F1", f"{f1_score(y_true, y_pred, zero_division=0):.3f}")
            if y_true.nunique() == 2:
                st.metric("ROC-AUC", f"{roc_auc_score(y_true, y_prob):.3f}")

st.divider()
st.caption(
    "Important: this app analyzes uploaded historical/session CSV data. It is not connected "
    "to a live store or tracking visitors automatically. Predictions are estimates, not guarantees. "
    "The suggested actions are illustrative business rules."
)
